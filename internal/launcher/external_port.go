// PortView describes an observed listener, not a process managed by LAL.
type PortView struct {
	PID            int    `json:"pid"`
	Command        string `json:"command"`
	Directory      string `json:"directory"`
	Identity       string `json:"identity"`
	MatchesProject bool   `json:"matchesProject"`
	Accessible     bool   `json:"accessible"`
	PreviewOnly    bool   `json:"previewOnly"`
}

func isNativeGame(service Service) bool {
	if normalizeModule(service.Module) != moduleGame {
		return false
	}
	cmd := strings.ToLower(strings.TrimSpace(service.Command))
	// Only recognize the native launch commands generated by project detection.
	return strings.HasPrefix(cmd, "godot ") || strings.HasPrefix(cmd, "godot\t") ||
		strings.HasPrefix(cmd, "'/applications/godot.app/contents/macos/godot'") ||
		strings.HasPrefix(cmd, "/applications/godot.app/contents/macos/godot ") ||
		strings.HasPrefix(cmd, "open -a unity ")
}

func managedAccessURL(service Service) string {
	if isNativeGame(service) {
		return ""
	}
	return service.URL
}

func inspectExternalPort(service Service) *PortView {
	_, pid := accessPortOwner(service.URL)
	if pid <= 0 {
		return nil
	}
	output, err := boundedCommand("/bin/ps", "-p", strconv.Itoa(pid), "-o", "lstart=", "-o", "command=")
	if err != nil {
		return nil
	}
	identity := strings.TrimSpace(string(output))
	cwdOutput, _ := boundedCommand("/usr/sbin/lsof", "-a", "-p", strconv.Itoa(pid), "-d", "cwd", "-Fn")
	directory := ""
	for _, line := range strings.Split(string(cwdOutput), "\n") {
		if strings.HasPrefix(line, "n/") {
			directory = line[1:]
			break
		}
	}
	actual, aErr := filepath.EvalSymlinks(directory)
	project, pErr := filepath.EvalSymlinks(service.Directory)
	matches := aErr == nil && pErr == nil && actual == project
	accessible, _ := probeAccessURL(service.URL, 200*time.Millisecond)
	return &PortView{PID: pid, Command: identity, Directory: directory,
		Identity: identity, MatchesProject: matches, Accessible: accessible, PreviewOnly: isNativeGame(service)}
}

// StopExternalAndStart verifies the listener has not changed since confirmation.
func (m *serviceManager) StopExternalAndStart(id string, pid int, identity string) error {
	service, err := m.serviceByID(id)
	if err != nil {
		return err
	}
	if isNativeGame(service) {
		return fmt.Errorf("原生游戏与预览服务独立，请直接启动游戏")
	}
	m.mu.RLock()
	_, running := m.processes[id]
	transitioning := m.lastStatus[id] == "starting" || m.lastStatus[id] == "stopping"
	m.mu.RUnlock()
	if running || transitioning {
		return fmt.Errorf("服务状态已变化，请刷新后重试")
	}
	if pid <= 1 || pid == os.Getpid() {
		return fmt.Errorf("不能停止该进程")
	}
	group, groupErr := syscall.Getpgid(pid)
	m.mu.RLock()
	for _, process := range m.processes {
		if groupErr == nil && group == process.cmd.Process.Pid {
			running = true
		}
	}
	for _, process := range m.scriptProcesses {
		if groupErr == nil && group == process.cmd.Process.Pid {
			running = true
		}
	}
	m.mu.RUnlock()
	if running {
		return fmt.Errorf("该进程由 LAL 管理，请在对应项目中停止")
	}
	owner := inspectExternalPort(service)
	if owner == nil || !owner.MatchesProject || owner.PID != pid || identity == "" || owner.Identity != identity {
		return fmt.Errorf("端口占用进程已变化或项目目录不匹配，请刷新后重试")
	}
	if err := syscall.Kill(pid, syscall.SIGTERM); err != nil {
		return fmt.Errorf("停止外部进程失败：%w", err)
	}
	deadline := time.Now().Add(5 * time.Second)
	for time.Now().Before(deadline) {
		if inspectExternalPort(service) == nil {
			return m.StartService(id)
		}
		time.Sleep(100 * time.Millisecond)
	}
	return fmt.Errorf("已发送停止信号，但端口仍被占用；请检查进程是否自动重启")
}

// Match the configured address as well as the port; another loopback address
// may legitimately have its own listener on the same port.
func accessPortOwner(accessURL string) (string, int) {
	parsed, err := url.Parse(accessURL)
	if err != nil {
		return "", 0
	}
	host := strings.ToLower(parsed.Hostname())
	ip := net.ParseIP(host)
	if host != "localhost" && (ip == nil || !ip.IsLoopback()) {
		return "", 0
	}
	port := parsed.Port()
	if port == "" {
		if parsed.Scheme == "https" {
			port = "443"
		} else {
			port = "80"
		}
	}
	output, err := boundedCommand("/usr/sbin/lsof", "-nP", "-iTCP:"+port, "-sTCP:LISTEN", "-Fpcn")
	if err != nil {
		return "", 0
	}
	pid, command := 0, ""
	for _, line := range strings.Split(string(output), "\n") {
		if len(line) < 2 {
			continue
		}
		switch line[0] {
		case 'p':
			pid, _ = strconv.Atoi(line[1:])
			command = ""
		case 'c':
			command = line[1:]
		case 'n':
			address, _, err := net.SplitHostPort(line[1:])
			if err != nil {
				continue
			}
			listenerIP := net.ParseIP(address)
			matches := address == "*" || (listenerIP != nil && listenerIP.IsUnspecified()) ||
				(host == "localhost" && listenerIP != nil && listenerIP.IsLoopback()) || (ip != nil && ip.Equal(listenerIP))
			if matches {
				return command, pid
			}
		}
	}
	return "", 0
}

func boundedCommand(name string, args ...string) ([]byte, error) {
	ctx, cancel := context.WithTimeout(context.Background(), time.Second)
	defer cancel()
	return exec.CommandContext(ctx, name, args...).Output()
}
